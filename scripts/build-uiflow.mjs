// Bundle the standalone engine with Next's pinned webpack; no extra runtime or package dependency.
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { readFile, mkdtemp, rm } from "node:fs/promises";

const require = createRequire(import.meta.url);
const { webpack } = require("next/dist/compiled/webpack/webpack");
import { tmpdir } from "node:os";
import { join } from "node:path";

const check = process.argv.includes("--check");
const temporary = check ? await mkdtemp(join(tmpdir(), "uiflow-check-")) : null;
const root = fileURLToPath(new URL("../", import.meta.url));
const compiler = webpack({
  mode: "none",
  context: root,
  entry: "./web/src/features/youtrack/flow-engine/index.js",
  output: {
    path: temporary ?? fileURLToPath(new URL("../web/public/", import.meta.url)),
    filename: "uiflow.js",
    iife: true,
  },
  devtool: false,
  optimization: { concatenateModules: true, usedExports: true, minimize: false },
  plugins: [new webpack.BannerPlugin("Generated by npm run build:uiflow. Edit web/src/features/youtrack/flow-engine/.\nSelf-contained UIFlow engine for the dashboard and offline HTML exports.")],
});

try {
  const stats = await new Promise((resolve, reject) => compiler.run((error, result) => error ? reject(error) : resolve(result)));
  if (stats.hasErrors()) throw new Error(stats.toString({ all: false, errors: true }));
  // The backend embeds this file in an inline script, including when opened offline.
  const artifact = new URL("../web/public/uiflow.js", import.meta.url);
  const engine = await readFile(temporary ? join(temporary, "uiflow.js") : artifact, "utf8");
  if (check && engine !== await readFile(artifact, "utf8")) throw new Error("UI flow bundle is stale: run npm run build:uiflow");
  if (/<\/script/i.test(engine)) throw new Error("UI flow bundle contains a closing script tag");
  console.log(`UI flow engine ${check ? "verified" : "bundled"} (${Buffer.byteLength(engine)} bytes)`);
} finally {
  try {
    await new Promise((resolve, reject) => compiler.close((error) => error ? reject(error) : resolve()));
  } finally {
    if (temporary) await rm(temporary, { recursive: true, force: true });
  }
}
